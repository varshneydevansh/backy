import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const root = path.resolve(fs.existsSync('examples/custom-frontend-next/src/lib') ? 'examples/custom-frontend-next/src/lib' : 'src/lib');
const cache = new Map();
function load(name) {
  const file = path.join(root, `${name}.tsx`);
  if (cache.has(file)) return cache.get(file);
  const source = fs.readFileSync(file, 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2022 } }).outputText;
  const mod = { exports: {} };cache.set(file, mod.exports);
  new Function('require', 'module', 'exports', compiled)(specifier => specifier.startsWith('./') ? load(specifier.slice(2)) : require(specifier), mod, mod.exports);
  return mod.exports;
}
const { BackyPage } = load('render');
const element = { id: 'widget', type: 'codeComponent', componentKey: 'fixture.counter', version: '1.0.0', props: { componentKey: 'fixture.counter', version: '1.0.0', start: 3, sandboxUrl: 'https://untrusted.example/steal', fallback: { title: 'Counter fallback', text: 'Static summary' }, renderCapabilities: { hydrationMode: 'sandbox-iframe' } } };
const payload = { site: { id: 'fixture-site' }, route: { path: '/counter' }, content: { elements: [element] }, navigation: { primary: [] }, assets: { media: [] }, interactions: {}, seo: {} };
const html = renderToStaticMarkup(React.createElement(BackyPage, { payload, publicApiBaseUrl: 'https://cms.example/api' }));
assert.match(html, /<iframe/, 'A separate frontend must render the sandboxed widget instead of an empty paragraph');
assert(html.includes('https://cms.example/api/sites/fixture-site/interactive-components/fixture.counter/1.0.0/sandbox'));
assert(html.includes('sandbox="allow-scripts allow-forms"'));
assert(!html.includes('allow-same-origin') && !html.includes('https://untrusted.example/steal'));
assert(html.includes('Counter fallback') && html.includes('Static summary'));
const runtime = load('interactive');
assert.equal(runtime.sandboxComponentUrl('javascript:alert(1)', 'site', 'key', '1.0.0'), '');
assert.equal(runtime.sandboxComponentUrl('https://user:pass@cms.example/api', 'site', 'key', '1.0.0'), '');
assert.equal(runtime.sandboxComponentUrl('https://cms.example/api', 'site/x', 'key/x', 'v/x'), 'https://cms.example/api/sites/site%2Fx/interactive-components/key%2Fx/v%2Fx/sandbox');
const frame = {};const message = { protocol: 'backy.interactive-component.v1', componentKey: 'fixture.counter', version: '1.0.0', type: 'backy.interactive-component.ready' };
assert(runtime.isWidgetMessage(frame, frame, message, 'fixture.counter', '1.0.0'));
for (const [source, data] of [[{}, message], [frame, { ...message, version: '2.0.0' }], [frame, { ...message, componentKey: 'other' }], [frame, { ...message, protocol: 'other' }], [frame, { ...message, version: undefined }]]) assert(!runtime.isWidgetMessage(source, frame, data, 'fixture.counter', '1.0.0'));
const init = runtime.widgetInitPayload(element);
assert.equal(init.props.start, 3);
assert(!('sandboxUrl' in init.props) && !('renderCapabilities' in init.props) && !('fallback' in init.props));
assert.equal(init.componentKey, 'fixture.counter');
assert.equal(init.version, '1.0.0');
const unknown = renderToStaticMarkup(React.createElement(BackyPage, { payload: { ...payload, content: { elements: [{ ...element, type: 'interactiveFigure', props: { ...element.props, renderCapabilities: { hydrationMode: 'trusted-component' } } }] } }, publicApiBaseUrl: 'https://cms.example/api' }));
assert(!unknown.includes('<iframe') && unknown.includes('Static summary'), 'Unmapped trusted components retain their fallback');
