import { createHash, randomUUID } from 'node:crypto';
import type { FormDefinition } from '@backy-cms/core';
import type { StorageAdapter } from '@backy/storage';
import { scanMediaUploadWithProviders } from './mediaSafety';
import { isUploadAllowedByFileType, readMediaBillingLimit, resolveMediaUploadPolicy } from './mediaUploadPolicy';
import { getFormAttachmentStorage } from './formAttachmentStorage';
import { FORM_SUBMISSION_FILE_LIMITS } from './formSubmissionTransport';

export const FORM_ATTACHMENT_KIND = 'backy.form.attachment.v1';
// Leave envelope room below Vercel's 4.5 MB request/response payload limit.
export const FORM_ATTACHMENT_LIMITS = { ...FORM_SUBMISSION_FILE_LIMITS, maxRequestBytes: FORM_SUBMISSION_FILE_LIMITS.maxTotalBytes + 256 * 1024 };
export type FormAttachment = { kind: typeof FORM_ATTACHMENT_KIND; id: string; attachmentId: string; filename: string; mimeType: string; sizeBytes: number };
type PendingAttachment = { fieldKey: string; file: File; reference: FormAttachment };
export class FormAttachmentError extends Error {
  constructor(public status: number, public code: string, message: string) { super(message); }
}
const object = (value: unknown): value is Record<string, unknown> => !!value && typeof value === 'object' && !Array.isArray(value);
export const isFormAttachment = (value: unknown): value is FormAttachment => object(value)
  && value.kind === FORM_ATTACHMENT_KIND && typeof value.attachmentId === 'string' && /^[a-f0-9-]{36}$/.test(value.attachmentId)
  && value.id === value.attachmentId && typeof value.filename === 'string' && typeof value.mimeType === 'string'
  && typeof value.sizeBytes === 'number' && Number.isSafeInteger(value.sizeBytes) && value.sizeBytes > 0;
export const formAttachmentsFromValues = (values: Record<string, unknown>): FormAttachment[] => Object.values(values).flatMap((value) => (Array.isArray(value) ? value : [value]).filter(isFormAttachment));
export const formAttachmentPath = (siteId: string, formId: string, attachmentId: string) => `form-attachments/sites/${createHash('sha256').update(siteId).digest('hex')}/forms/${createHash('sha256').update(formId).digest('hex')}/${attachmentId}`;
const uploadWindows = new Map<string, { count: number; startedAt: number }>();
export function admitFormAttachmentUpload(siteId: string, formId: string, ipHash: string | null, submissions: { formId: string; ipHash?: string | null; submittedAt: string; values: Record<string, unknown> }[]) {
  const now = Date.now(), key = createHash('sha256').update(JSON.stringify([siteId, formId, ipHash || 'unknown'])).digest('hex');
  for (const [key, window] of uploadWindows) if (now - window.startedAt >= 60_000) uploadWindows.delete(key);
  const window = uploadWindows.get(key) || { count: 0, startedAt: now };
  window.count++; uploadWindows.set(key, window);
  const recent = submissions.filter((submission) => submission.formId === formId && (submission.ipHash || null) === ipHash && now - Date.parse(submission.submittedAt) < 60_000 && formAttachmentsFromValues(submission.values).length > 0);
  if (window.count > 5 || recent.length >= 5) throw new FormAttachmentError(429, 'FORM_ATTACHMENT_RATE_LIMITED', 'Wait one minute before uploading more form files.');
}

async function boundedBody(request: Request, maximum: number): Promise<Buffer> {
  const length = request.headers.get('content-length');
  if (length && (!/^\d+$/.test(length) || Number(length) > maximum)) throw new FormAttachmentError(413, 'FORM_REQUEST_TOO_LARGE', 'The form request exceeds the attachment limit.');
  const reader = request.body?.getReader();
  if (!reader) return Buffer.alloc(0);
  const chunks: Buffer[] = []; let size = 0;
  try {
    for (;;) {
      const next = await reader.read(); if (next.done) break;
      size += next.value.byteLength;
      if (size > maximum) { await reader.cancel(); throw new FormAttachmentError(413, 'FORM_REQUEST_TOO_LARGE', 'The form request exceeds the attachment limit.'); }
      chunks.push(Buffer.from(next.value));
    }
  } finally { reader.releaseLock(); }
  return Buffer.concat(chunks);
}
function rejectForgedReferences(value: unknown): void {
  if (Array.isArray(value)) { value.forEach(rejectForgedReferences); return; }
  if (!object(value)) return;
  if (value.kind === FORM_ATTACHMENT_KIND) throw new FormAttachmentError(400, 'FORGED_FORM_ATTACHMENT', 'Attachment references must be generated by a file upload.');
  Object.values(value).forEach(rejectForgedReferences);
}
export async function readFormSubmissionRequest(request: Request, form: FormDefinition, fieldAliases: Record<string, string> = {}) {
  const pending: PendingAttachment[] = [];
  if (!request.headers.get('content-type')?.toLowerCase().startsWith('multipart/form-data')) {
    const bytes = await boundedBody(request, 256 * 1024);
    const raw: unknown = (() => { try { return JSON.parse(bytes.toString('utf8')); } catch { return null; } })();
    rejectForgedReferences(raw);
    return { raw, pending };
  }
  const bytes = await boundedBody(request, FORM_ATTACHMENT_LIMITS.maxRequestBytes);
  let data: FormData;
  try { data = await new Request(request.url, { method: 'POST', headers: { 'content-type': request.headers.get('content-type') || '' }, body: new Uint8Array(bytes) }).formData(); }
  catch { throw new FormAttachmentError(400, 'INVALID_FORM_MULTIPART', 'Unable to read the form files.'); }
  const payload = data.get('payload');
  let raw: Record<string, unknown> = {};
  if (payload !== null) {
    if (typeof payload !== 'string' || Buffer.byteLength(payload) > 256 * 1024) throw new FormAttachmentError(400, 'INVALID_FORM_MULTIPART', 'The form payload must be JSON text within 256 KB.');
    try { const parsed: unknown = JSON.parse(payload); if (!object(parsed)) throw new Error(); raw = parsed; }
    catch { throw new FormAttachmentError(400, 'INVALID_FORM_MULTIPART', 'The form payload must be JSON text.'); }
  }
  rejectForgedReferences(raw);
  const values: Record<string, unknown> = object(raw.values) ? { ...raw.values } : {};
  let total = 0, textBytes = 0;
  for (const [key, value] of data.entries()) {
    if (key === 'payload') continue;
    if (typeof value === 'string') {
      textBytes += Buffer.byteLength(key) + Buffer.byteLength(value);
      if (textBytes > 256 * 1024) throw new FormAttachmentError(413, 'FORM_TEXT_LIMIT_EXCEEDED', 'Form text fields must fit within 256 KB.');
      if (payload !== null) throw new FormAttachmentError(400, 'INVALID_FORM_MULTIPART', 'Text fields must be inside the form payload.');
      if (['honeypot', 'startedAt', 'captchaToken', 'requestId', 'pageId', 'postId'].includes(key)) raw[key] = value;
      else values[key] = values[key] === undefined ? value : [...(Array.isArray(values[key]) ? values[key] as unknown[] : [values[key]]), value];
      continue;
    }
    if (!value.size && !value.name) continue;
    const fieldKey = form.fields.some((field) => field.key === key) ? key : fieldAliases[key];
    const field = form.fields.find((candidate) => candidate.key === fieldKey);
    if (!field || field.type !== 'file') throw new FormAttachmentError(400, 'UNDECLARED_FORM_FILE', 'Files must use a declared file field.');
    if (value.size <= 0) throw new FormAttachmentError(400, 'EMPTY_FORM_FILE', 'Uploaded files must not be empty.');
    total += value.size;
    if (value.size > FORM_ATTACHMENT_LIMITS.maxFileBytes || total > FORM_ATTACHMENT_LIMITS.maxTotalBytes || pending.length >= FORM_ATTACHMENT_LIMITS.maxFiles) throw new FormAttachmentError(413, 'FORM_FILE_LIMIT_EXCEEDED', 'Use at most 5 files and 4 MB in total.');
    const attachmentId = randomUUID();
    const filename = (value.name.replace(/\\/g, '/').split('/').pop() || 'attachment').replace(/[\u0000-\u001f\u007f]/g, '').slice(0, 180) || 'attachment';
    const reference: FormAttachment = { kind: FORM_ATTACHMENT_KIND, id: attachmentId, attachmentId, filename, mimeType: value.type || 'application/octet-stream', sizeBytes: value.size };
    pending.push({ fieldKey, file: value, reference });
    // Only these server-generated references enter field validation/persistence.
    const previous = pending.filter((attachment) => attachment.fieldKey === fieldKey).map((attachment) => attachment.reference);
    values[fieldKey] = previous;
  }
  raw.values = values;
  return { raw, pending };
}
export async function storeFormAttachments(input: { siteId: string; formId: string; pending: PendingAttachment[]; settings: Parameters<typeof resolveMediaUploadPolicy>[0]; siteSettings?: unknown; currentUsageBytes: number }) {
  const policy = resolveMediaUploadPolicy(input.settings);
  const nextUsageBytes = input.currentUsageBytes + input.pending.reduce((total, file) => total + file.file.size, 0);
  if (nextUsageBytes > policy.quotaBytes || readMediaBillingLimit(input.siteSettings, input.settings, nextUsageBytes).blocked) throw new FormAttachmentError(413, 'SITE_MEDIA_QUOTA_EXCEEDED', 'The site storage quota cannot accept these files.');
  const prepared: { reference: FormAttachment; buffer: Buffer }[] = [];
  for (const attachment of input.pending) {
    if (attachment.file.size > policy.maxUploadBytes || !isUploadAllowedByFileType(policy, { filename: attachment.reference.filename, mimeType: attachment.reference.mimeType })) throw new FormAttachmentError(415, 'FORM_FILE_TYPE_NOT_ALLOWED', 'The file does not meet the site upload policy.');
    const buffer = Buffer.from(await attachment.file.arrayBuffer());
    const mimeType = attachment.reference.mimeType;
    const mediaType = mimeType.startsWith('image/') ? 'image' : mimeType.startsWith('audio/') ? 'audio' : mimeType.startsWith('video/') ? 'video' : 'document';
    await scanMediaUploadWithProviders({ buffer, originalName: attachment.reference.filename, mimeType, mediaType });
    prepared.push({ reference: attachment.reference, buffer });
  }
  const storage: StorageAdapter = await getFormAttachmentStorage();
  const paths: string[] = [];
  const cleanup = async () => {
    const failures = await Promise.allSettled(paths.map((path) => storage.delete(path)));
    if (failures.some((result) => result.status === 'rejected')) throw new FormAttachmentError(503, 'FORM_ATTACHMENT_CLEANUP_FAILED', 'Unable to clean up an incomplete attachment upload.');
  };
  try {
    for (const attachment of prepared) {
      const path = formAttachmentPath(input.siteId, input.formId, attachment.reference.attachmentId);
      // Track the path before upload, including a provider that writes then reports failure.
      paths.push(path);
      const uploaded = await storage.upload(attachment.buffer, { path, filename: attachment.reference.filename, mimeType: attachment.reference.mimeType, cacheControl: 'private, no-store', contentDisposition: 'attachment' });
      if (uploaded.path !== path || uploaded.size !== attachment.buffer.length) throw new FormAttachmentError(503, 'FORM_ATTACHMENT_STORAGE_FAILED', 'The attachment upload was incomplete.');
    }
  } catch (error) { await cleanup(); throw error; }
  return { cleanup };
}
