/** Assert a captured disposable actual-handler/browser journey; does not fabricate browser proof. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const path=process.argv[2];
assert(path, 'Pass the captured /fixture/evidence JSON path.');
const evidence=JSON.parse(readFileSync(path,'utf8'));
const post=evidence.posts.find(post=>post.slug==='registered-article-journey');
assert(post);assert.equal(post.status,'archived');
const content=post.content;
const walk=nodes=>nodes.flatMap(node=>[node,...walk(node.children||[])]);
const elements=walk(content.elements);
const body=elements.find(node=>node.id==='article-body-proof');
assert(body);assert.equal(body.props.fontFamily,'Georgia');assert.equal(body.styles.maxWidth,'100ch');
const rich=walk(body.props.content);
for(const type of ['code_block','img','media_embed','table','data_figure','collapsible']) assert(rich.some(node=>node.type===type),`Saved ${type}`);
assert(rich.some(node=>node.bold&&node.text.includes('verified bold text')));
assert(rich.some(node=>node.text==='Fast proof.'));assert(rich.some(node=>node.text==='Second proof.'));
assert(rich.some(node=>node.text==='let proof=1;'));
const audio=elements.find(node=>node.type==='audio');assert(audio?.props.mediaId);assert.equal(audio.props.controls,true);assert.equal(audio.responsive.mobile.x,28);
assert.equal(content.canvasSize.width,1200);assert.equal(content.canvasSize.responsive.mobile.width,390);
assert.deepEqual(content.metadata.extension.retained,[false,0,{nested:true}]);
assert.deepEqual(content.contentDocument.metadata.extension.retained,[false,0,{nested:true}]);
assert.deepEqual(elements.find(node=>node.id==='site-header-proof').props.extension.retained,[false,0]);
assert(elements.some(node=>node.id==='site-footer-proof'));assert(content.assets.fonts.some(font=>font.family==='Georgia'));
const persisted=evidence.persistedPosts.find(row=>row.id===post.id);assert(persisted);assert.equal(persisted.status,'archived');
assert.deepEqual(persisted.content.elements,content.elements);
const requests=evidence.requests;
for(const [method,suffix,status] of [['PATCH',post.id,200],['GET',post.id,200],['POST','/preview',200],['POST','/publish',200],['POST','/archive',200]]) assert(requests.some(request=>request.method===method&&request.path.endsWith(suffix)&&request.status===status));
assert(requests.some(request=>request.path.endsWith('/preview')&&request.cache==='private, no-store'));
assert(requests.some(request=>request.path.endsWith('/render')&&request.status===200));assert.equal(requests.filter(request=>request.path.endsWith('/render')).at(-1).status,404);
assert(requests.every(request=>!request.path.includes('?')),'Trace omits private preview tokens.');
assert(evidence.frontendDesign.templates.some(template=>template.id==='registered-article-proof'&&template.type==='blogPost'));
console.log('Captured registered blog evidence passed: actual persisted rich blocks/chrome/fonts/media/responsive content, focus save/reopen, preview/publish/withdraw transport. Browser screenshots/console and provider bounds remain separate evidence.');
